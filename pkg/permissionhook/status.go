package permissionhook

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Hook installation modes reported by InspectHook.
const (
	ModePermissionRequest = "permissionRequest"
	ModeScopedPreToolUse  = "scoped preToolUse"
	ModeAllPreToolUse     = "all-rules preToolUse"
)

// Effective hook states reported by HookStatus.State.
const (
	StateNotInstalled = "not installed"
	StateUnmanaged    = "unmanaged"
	StateConfigError  = "config error"
	StateDisabled     = "disabled"
	StateNoConfig     = "no config"
	StateActive       = "active"
)

// HookStatus describes the installed hook config file and the rules it uses.
type HookStatus struct {
	HookPath   string
	Installed  bool
	Managed    bool
	HookError  error
	Mode       string
	Exec       string
	TimeoutSec int
	// ConfigPinned is true when the hook passes --config explicitly.
	ConfigPinned bool
	Config       ConfigStatus
	LogPath      string
	LogPathError error
	// ConflictingHooks lists other files in the hook directory that register
	// permissionRequest hooks, which can prevent scoped preToolUse approvals.
	ConflictingHooks []string
	NeedsReinstall   bool
}

// ConfigStatus summarizes the rules config file used by the hook.
type ConfigStatus struct {
	Path              string
	Found             bool
	Disabled          bool
	LoggingDisabled   bool
	Error             error
	AllowCommands     int
	AllowGHRead       bool
	AllowGitRead      bool
	AllowShellDisplay bool
	AllowTools        int
	ScopedTools       int
	DenyCommands      int
	DenyTools         int
}

// State returns the effective hook state.
func (s *HookStatus) State() string {
	switch {
	case !s.Installed:
		return StateNotInstalled
	case !s.Managed:
		return StateUnmanaged
	case s.Config.Error != nil:
		return StateConfigError
	case s.Config.Disabled:
		return StateDisabled
	case !s.Config.Found:
		return StateNoConfig
	default:
		return StateActive
	}
}

type managedHook struct {
	mode       string
	exec       string
	configPath string
	timeoutSec int
}

var hookCommands = map[string]struct{ event, mode string }{
	"permission-request": {"permissionRequest", ModePermissionRequest},
	"pre-tool-use":       {"preToolUse", ModeScopedPreToolUse},
}

// parseManagedHook reports whether data is a hook config generated by InstallHook:
// one entry in a single supported event invoking "hook permission-request" or
// "hook pre-tool-use".
func parseManagedHook(data []byte) (*managedHook, error) {
	var f hookFile
	if err := json.Unmarshal(data, &f); err != nil {
		return nil, err
	}
	if f.Version != 1 || len(f.Hooks) != 1 {
		return nil, nil
	}
	for event, entries := range f.Hooks {
		if len(entries) != 1 {
			return nil, nil
		}
		e := entries[0]
		if e.Type != "command" {
			return nil, nil
		}
		executable := filepath.Base(e.Exec)
		for i := 0; i+1 < len(e.Args); i++ {
			if e.Args[i] != "hook" {
				continue
			}
			if !((executable == "gh" || executable == "gh.exe") && i == 1 && e.Args[0] == "copilot-attendant") &&
				!((executable == "gh-copilot-attendant" || executable == "gh-copilot-attendant.exe") && i == 0) {
				return nil, nil
			}
			cmd, ok := hookCommands[e.Args[i+1]]
			if !ok || cmd.event != event {
				return nil, nil
			}
			h := &managedHook{mode: cmd.mode, exec: e.Exec, timeoutSec: e.TimeoutSec}
			rest := e.Args[i+2:]
			for j := 0; j < len(rest); j++ {
				if rest[j] == "--all-rules" && h.mode == ModeScopedPreToolUse {
					h.mode = ModeAllPreToolUse
				}
				if rest[j] == "--config" && j+1 < len(rest) {
					h.configPath = rest[j+1]
					j++
				}
			}
			return h, nil
		}
	}
	return nil, nil
}

// InspectHook reads the hook config at hookPath (default DefaultHookPath()) and the
// rules config it uses. configPath overrides the config used when the hook does not
// pin one; it otherwise follows ResolveConfigPath.
func InspectHook(hookPath, configPath string) (*HookStatus, error) {
	if hookPath == "" {
		p, err := DefaultHookPath()
		if err != nil {
			return nil, err
		}
		hookPath = p
	}
	st := &HookStatus{HookPath: hookPath}
	st.LogPath, st.LogPathError = HookLogPath()
	data, err := os.ReadFile(hookPath)
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return nil, err
	default:
		st.Installed = true
		h, perr := parseManagedHook(data)
		if perr != nil {
			st.HookError = perr
		} else if h != nil {
			st.Managed = true
			st.Mode = h.mode
			st.Exec = h.exec
			st.TimeoutSec = h.timeoutSec
			if h.configPath != "" {
				st.ConfigPinned = true
				configPath = h.configPath
			}
		}
	}

	resolved, err := ResolveConfigPath(configPath)
	if err != nil {
		return nil, err
	}
	st.Config = inspectConfig(resolved, st.Mode)
	if st.Mode == ModeScopedPreToolUse || st.Mode == ModeAllPreToolUse {
		st.ConflictingHooks = findPermissionRequestHooks(hookPath)
	}
	if st.Mode == ModePermissionRequest && st.Config.Found && st.Config.Error == nil {
		cfg, _, err := LoadConfig(resolved)
		if err != nil {
			return nil, err
		}
		st.NeedsReinstall = needsPreToolUse(cfg)
	}
	return st, nil
}

func inspectConfig(p, mode string) ConfigStatus {
	cs := ConfigStatus{Path: p}
	cfg, found, err := LoadConfig(p)
	cs.Found = found
	if err != nil {
		cs.Error = err
		return cs
	}
	cs.Disabled = cfg.Hooks.Disabled
	cs.LoggingDisabled = cfg.Hooks.Logging.Disabled
	if cs.Disabled {
		return cs
	}
	pr := cfg.Hooks.PermissionRequest
	cs.AllowCommands = len(pr.Allow.Commands)
	cs.AllowGHRead = pr.Allow.GHRead
	cs.AllowGitRead = pr.Allow.GitRead
	cs.AllowShellDisplay = pr.Allow.ShellDisplay
	cs.AllowTools = len(pr.Allow.Tools)
	cs.ScopedTools = len(pr.Allow.ScopedTools)
	cs.DenyCommands = len(pr.Deny.Commands)
	cs.DenyTools = len(pr.Deny.Tools)
	if found && mode == ModeScopedPreToolUse {
		if err := validatePreToolConfig(cfg); err != nil {
			cs.Error = err
		}
	}
	return cs
}

func findPermissionRequestHooks(hookPath string) []string {
	dir := filepath.Dir(hookPath)
	matches, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil {
		return nil
	}
	self, _ := filepath.Abs(hookPath)
	var found []string
	for _, m := range matches {
		if abs, _ := filepath.Abs(m); abs == self {
			continue
		}
		data, err := os.ReadFile(m)
		if err != nil {
			continue
		}
		var f struct {
			Hooks map[string]json.RawMessage `json:"hooks"`
		}
		if json.Unmarshal(data, &f) != nil {
			continue
		}
		if _, ok := f.Hooks["permissionRequest"]; ok {
			found = append(found, m)
		}
	}
	sort.Strings(found)
	return found
}

// WriteStatus prints a human-readable hook status report.
func WriteStatus(w io.Writer, st *HookStatus) error {
	var b strings.Builder
	fmt.Fprintf(&b, "State:   %s\n", st.State())
	fmt.Fprintf(&b, "Hook:    %s", st.HookPath)
	switch {
	case !st.Installed:
		b.WriteString(" (not found)\n")
	case st.HookError != nil:
		fmt.Fprintf(&b, " (unreadable: %v)\n", st.HookError)
	case !st.Managed:
		b.WriteString(" (not generated by hook install)\n")
	default:
		b.WriteString("\n")
		fmt.Fprintf(&b, "Mode:    %s\n", st.Mode)
		fmt.Fprintf(&b, "Exec:    %s\n", st.Exec)
		fmt.Fprintf(&b, "Timeout: %ds\n", st.TimeoutSec)
	}
	cs := st.Config
	logging := "enabled"
	switch {
	case cs.Error != nil:
		logging = "stopped (config error)"
	case cs.Disabled:
		logging = "disabled (hook disabled)"
	case cs.LoggingDisabled:
		logging = "disabled"
	case !loggingSupported():
		logging = "unsupported on this platform"
	}
	fmt.Fprintf(&b, "Logging: %s\n", logging)
	if st.LogPathError != nil {
		b.WriteString("Log:     unavailable\n")
	} else {
		fmt.Fprintf(&b, "Log:     %s\n", st.LogPath)
	}
	pinned := ""
	if st.ConfigPinned {
		pinned = ", pinned by hook"
	}
	switch {
	case cs.Error != nil:
		fmt.Fprintf(&b, "Config:  %s (error%s: %v)\n", cs.Path, pinned, cs.Error)
	case !cs.Found:
		fmt.Fprintf(&b, "Config:  %s (not found%s)\n", cs.Path, pinned)
	case cs.Disabled:
		fmt.Fprintf(&b, "Config:  %s (disabled%s)\n", cs.Path, pinned)
	default:
		fmt.Fprintf(&b, "Config:  %s (enabled%s)\n", cs.Path, pinned)
		fmt.Fprintf(&b, "Rules:   allow commands=%d ghRead=%t gitRead=%t shellDisplay=%t tools=%d scopedTools=%d, deny commands=%d tools=%d\n",
			cs.AllowCommands, cs.AllowGHRead, cs.AllowGitRead, cs.AllowShellDisplay, cs.AllowTools, cs.ScopedTools, cs.DenyCommands, cs.DenyTools)
	}
	for _, c := range st.ConflictingHooks {
		fmt.Fprintf(&b, "Warning: %s registers permissionRequest and can prevent scoped approvals\n", c)
	}
	if st.NeedsReinstall {
		b.WriteString("Warning: configured rules require preToolUse; reinstall the hook with --force\n")
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// ResolveHookConfigPath returns explicit when set, then the config path pinned by the
// managed hook at hookPath (default DefaultHookPath()), then ResolveConfigPath("").
func ResolveHookConfigPath(hookPath, explicit string) (string, error) {
	if explicit != "" {
		return explicit, nil
	}
	if hookPath == "" {
		p, err := DefaultHookPath()
		if err != nil {
			return "", err
		}
		hookPath = p
	}
	if data, err := os.ReadFile(hookPath); err == nil {
		if h, err := parseManagedHook(data); err == nil && h != nil && h.configPath != "" {
			return h.configPath, nil
		}
	}
	return ResolveConfigPath("")
}
