package hook

import (
	"fmt"

	"github.com/spf13/cobra"
	"github.com/srz-zumix/gh-copilot-attendant/pkg/permissionhook"
)

// NewStatusCmd creates the "status" command.
func NewStatusCmd() *cobra.Command {
	var hookPath, configPath string

	cmd := &cobra.Command{
		Use:   "status",
		Short: "Show the installed Copilot CLI hook and its config state",
		Long: `Show whether the hook config file exists and was generated by "hook install",
its mode (permissionRequest, scoped preToolUse, or all-rules preToolUse),
executable and timeout, and the
rules config it reads: path, whether it is enabled, disabled, missing, or invalid,
rule counts, and read preset states. In scoped mode, other files in the same hook directory that
register permissionRequest hooks are reported as warnings.

The hook file defaults to $COPILOT_HOME/hooks/gh-copilot-attendant.json (default
~/.copilot/hooks/gh-copilot-attendant.json); use --path to inspect another file.
A config path pinned by the hook wins; otherwise --config, then
$GH_COPILOT_ATTENDANT_CONFIG, then the default config path is used.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			st, err := permissionhook.InspectHook(hookPath, configPath)
			if err != nil {
				return fmt.Errorf("failed to inspect hook: %w", err)
			}
			return permissionhook.WriteStatus(cmd.OutOrStdout(), st)
		},
	}
	f := cmd.Flags()
	f.StringVar(&configPath, "config", "", "Config file path when the hook does not pin one")
	f.StringVar(&hookPath, "path", "", "Hook config file path")
	return cmd
}
