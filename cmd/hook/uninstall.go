package hook

import (
	"fmt"

	"github.com/spf13/cobra"
	"github.com/srz-zumix/gh-copilot-attendant/pkg/permissionhook"
)

// NewUninstallCmd creates the "uninstall" command.
func NewUninstallCmd() *cobra.Command {
	var path string
	var force bool

	cmd := &cobra.Command{
		Use:   "uninstall",
		Short: "Remove the Copilot CLI hook config",
		Long: `Remove the hook config file written by "hook install" from
$COPILOT_HOME/hooks/gh-copilot-attendant.json (default
~/.copilot/hooks/gh-copilot-attendant.json), or from --path. A file that was not
generated by "hook install" is kept unless --force is given. A missing file is not
an error. The rules config file is not removed; use "hook disable" to keep the hook
installed while ignoring all rules. Copilot CLI loads hooks when a session starts.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			dest, removed, err := permissionhook.UninstallHook(path, force)
			if err != nil {
				return fmt.Errorf("failed to uninstall hook: %w", err)
			}
			if !removed {
				_, err = fmt.Fprintf(cmd.OutOrStdout(), "No hook config found at %s\n", dest)
				return err
			}
			_, err = fmt.Fprintf(cmd.OutOrStdout(), "Removed hook config %s\n", dest)
			return err
		},
	}
	f := cmd.Flags()
	f.BoolVar(&force, "force", false, "Remove the file even if it was not generated by hook install")
	f.StringVar(&path, "path", "", "Hook config file path")
	return cmd
}
